// Results is everything the judge writes to results.json.
type Results struct {
	Config   Config
	Envs     []EnvDesc
	Aggs     []Agg
	Seconds  float64
	Notes    []string
	Protocol string // result of the line-protocol equivalence check
}

type EnvDesc struct {
	Name, Desc  string
	SettleLevel float64
	EpisodeCap  int
	Allowed     []string
}

func f2(x float64) string {
	if math.IsNaN(x) {
		return "–"
	}
	return fmt.Sprintf("%.2f", x)
}

func f0(x float64) string {
	if math.IsNaN(x) {
		return "–"
	}
	return fmt.Sprintf("%.0f", x)
}

// sparkline renders a curve as unicode blocks, scaled to [0, top].
func sparkline(c []float64, top float64) string {
	blocks := []rune("▁▂▃▄▅▆▇█")
	var b strings.Builder
	for _, v := range c {
		k := 0
		if top > 0 {
			k = int(math.Round(v / top * 7))
		}
		if k < 0 {
			k = 0
		}
		if k > 7 {
			k = 7
		}
		b.WriteRune(blocks[k])
	}
	return b.String()
}

func label(a Agg) string {
	if a.Feel == "-" {
		return a.Agent
	}
	return a.Agent + " (" + a.Feel + ")"
}

// WriteJSON writes results.json (curves and per-seed runs included).
func WriteJSON(path string, r Results) error {
	type aggOut struct {
		Agg
		RunsOut []RunResult `json:"Runs"`
	}
	out := struct {
		Results
		Aggs []aggOut
	}{Results: r}
	for _, a := range r.Aggs {
		ao := aggOut{Agg: a, RunsOut: a.Runs}
		for i := range ao.RunsOut {
			sanitize(&ao.RunsOut[i])
		}
		out.Aggs = append(out.Aggs, ao)
	}
	for i := range out.Aggs {
		nanToNeg(&out.Aggs[i].Agg)
	}
	b, err := json.MarshalIndent(out, "", " ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

func nn(x *float64) {
	if math.IsNaN(*x) || math.IsInf(*x, 0) {
		*x = -1
	}
}
func sanitize(r *RunResult) { nn(&r.EarlyRes); nn(&r.LateRes) }
func nanToNeg(a *Agg)       { nn(&a.EarlyRes); nn(&a.LateRes) }

// WriteMarkdown writes RESULTS.md.
func WriteMarkdown(path string, r Results, commentary map[string]string, summary string) error {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	c := r.Config
	w("# Grid world: baseline results\n\n")
	w("Generated by `go run ./cmd/judge` in %.0f s. %d steps per run, online (agents learn as they go, no separate training), seeds %v, view %dx%d. ",
		r.Seconds, c.Steps, c.Seeds, 2*c.Radius+1, 2*c.Radius+1)
	w("Energy is the environment's true total unease after each step; lower is better. Every number is a mean over seeds unless marked.\n\n")
	w("Agents: **idle** never acts; **random** picks uniformly among allowed actions; **reactive** is hand-written, moves towards the hottest felt cell and tries actions there, no learning; **qlearn** is tabular Q(λ) over the local view with reward = drop in felt energy on the same cells (see README); **qlearn-felt** is the identical learner with the literal reward \"drop in total felt energy\"; **oracle** sees the whole map and follows a scripted policy, a floor to read the others against, not a baseline.\n\n")
	w("Feel: **local** = per-cell energy of the 5x5 view; **global** = one number, the true total.\n\n")
	if summary != "" {
		w("%s\n\n", summary)
	}
	if r.Protocol != "" {
		w("Line protocol check: %s\n\n", r.Protocol)
	}
	writeSeparation(&b, r.Aggs)
	envOrder := []string{}
	byEnv := map[string][]Agg{}
	for _, a := range r.Aggs {
		if _, ok := byEnv[a.Env]; !ok {
			envOrder = append(envOrder, a.Env)
		}
		byEnv[a.Env] = append(byEnv[a.Env], a)
	}
	descs := map[string]EnvDesc{}
	for _, d := range r.Envs {
		descs[d.Name] = d
	}
	for _, en := range envOrder {
		as := byEnv[en]
		d := descs[en]
		w("## %s\n\n%s. Actions: %s. Settled when total energy ≤ %g.\n\n", en, d.Desc, strings.Join(d.Allowed, ", "), d.SettleLevel)
		if cm, ok := commentary[en]; ok {
			w("%s\n\n", cm)
		}
		top := 0.0
		for _, a := range as {
			for _, v := range a.Curve {
				top = math.Max(top, v)
			}
		}
		w("| agent | mean E | first-quarter E | **final-quarter E** (sd) | curve (0–%.0f) | first settle (median step) | time settled | resolve early → late (steps) | resolved by agent |\n", top)
		w("|---|---|---|---|---|---|---|---|---|\n")
		for _, a := range as {
			fs := "never"
			if a.FirstSettle >= 0 {
				fs = f0(a.FirstSettle)
			}
			w("| %s | %s | %s | **%s** (%s) | `%s` | %s | %.0f%% | %s → %s | %.0f%% |\n", label(a), f2(a.Mean), f2(a.Q1), f2(a.Q4), f2(a.Q4sd),
				sparkline(a.Curve, top), fs, 100*a.SettledFrac, f0(a.EarlyRes), f0(a.LateRes), 100*a.ByAgentFrac)
		}
		w("\n**Closed-world accounting** (totals per run). *Resolved* and *created* are true energy removed or added by the agent's own actions; *world added/removed* is the world's own dynamics. *Displaced* is energy the agent's actions moved from one cell to another without changing the total (carrying litter, wiping one plinth to fix another). *Felt relief* is the sum of every drop in what the agent felt; *look-away relief* is the part of it that came from moves alone, with the true total unchanged: problems leaving the view, not resolved. Under local feel, felt relief far above *resolved* means the agent mostly feels better by looking away.\n\n")
		w("| agent | resolved by agent | created by agent | displaced | world added | world removed | felt relief | look-away relief |\n|---|---|---|---|---|---|---|---|\n")
		for _, a := range as {
			if a.Agent == "idle" {
				continue
			}
			w("| %s | %.0f | %.0f | %.0f | %.0f | %.0f | %.0f | %.0f |\n", label(a), a.Resolved, a.Created, a.Displaced, a.WorldAdded, a.WorldRemoved, a.FeltRelief, a.LookAway)
		}
		// counters
		w("\n<details><summary>environment counters (per run)</summary>\n\n| agent | counters |\n|---|---|\n")
		for _, a := range as {
			var ks []string
			for k := range a.Counters {
				ks = append(ks, k)
			}
			sort.Strings(ks)
			var parts []string
			for _, k := range ks {
				parts = append(parts, fmt.Sprintf("%s %.1f", k, a.Counters[k]))
			}
			w("| %s | %s |\n", label(a), strings.Join(parts, ", "))
		}
		w("\n</details>\n\n")
		// transfer
		w("**Transfer** to a new layout of the same kind (%d steps): mean energy for a fresh agent vs the agent carried over from %d steps in the first layout. Ratio < 1 means experience helps in a layout it has never seen.\n\n", c.TransferSteps, c.Steps)
		w("| agent | fresh | carried over | ratio |\n|---|---|---|---|\n")
		for _, a := range as {
			if a.TransferFresh == 0 && a.TransferMoved == 0 {
				continue
			}
			w("| %s | %s | %s | %s |\n", label(a), f2(a.TransferFresh), f2(a.TransferMoved), f2(a.TransferMoved/a.TransferFresh))
		}
		w("\n")
		// branches
		hasBr := false
		for _, a := range as {
			if a.Branch != nil {
				hasBr = true
			}
		}
		if hasBr {
			w("**Learning checks** (learning agents only). Three futures of %d steps branch after the run: carry on; turn learning off (does what was learnt hold on its own?); a quiet period of %d steps with no input first (thinking without data; a model-free learner has nothing to do in it, so its two numbers should match).\n\n", c.MemorySteps, c.QuietSteps)
			w("| agent | carry on | learning off | after quiet |\n|---|---|---|---|\n")
			for _, a := range as {
				if a.Branch == nil {
					continue
				}
				w("| %s | %s | %s | %s |\n", label(a), f2(a.Branch.Continue), f2(a.Branch.LearningOff), f2(a.Branch.AfterQuiet))
			}
			w("\n")
		}
		// memory
		hasMem := false
		for _, a := range as {
			if a.Memory != nil {
				hasMem = true
			}
		}
		if hasMem {
			w("**External memory.** After the run, four futures of %d steps branch from the same moment: carry on; erase every mark the agent wrote; replace the agent with a fresh one but keep its marks; both. If written marks are used, erasing them should hurt the experienced agent, and keeping them should help the fresh one (compare the last two columns).\n\n", c.MemorySteps)
			w("| agent | marks written | steps with an old own mark in view | carry on | marks erased | fresh agent, marks kept | fresh agent, marks erased |\n|---|---|---|---|---|---|---|\n")
			for _, a := range as {
				if a.Memory == nil {
					continue
				}
				m := a.Memory
				w("| %s | %d | %.1f%% | %s | %s | %s | %s |\n", label(a), m.MarksWritten, 100*m.MarksSeenFrac, f2(m.Continue), f2(m.MarksErased), f2(m.AgentWiped), f2(m.BothWiped))
			}
			w("\n")
		}
	}
	for _, n := range r.Notes {
		w("%s\n\n", n)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// writeSeparation: one row per environment, final-quarter energy normalised
// so idle = 1 and oracle = 0, best learner vs best non-learner (both feels).
func writeSeparation(b *strings.Builder, aggs []Agg) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f, a...) }
	byEnv := map[string]map[string]Agg{}
	var order []string
	for _, a := range aggs {
		if byEnv[a.Env] == nil {
			byEnv[a.Env] = map[string]Agg{}
			order = append(order, a.Env)
		}
		byEnv[a.Env][label(a)] = a
	}
	w("## Overview\n\n")
	w("Final-quarter energy scaled so that **idle = 1** (nobody acts) and **oracle = 0** (full-information script). Lower is better; above 1 means the agent makes things worse than doing nothing. *Learning gain* is the learner's first-quarter minus final-quarter scaled energy: how much it improved within one run.\n\n")
	cols := []string{"random", "reactive (local)", "reactive (global)", "mapper (local)", "qlearn (local)", "qlearn (global)", "qlearn-felt (local)"}
	w("| env |")
	for _, c := range cols {
		w(" %s |", c)
	}
	w(" qlearn learning gain (local / global) |\n|---|")
	for range cols {
		w("---|")
	}
	w("---|\n")
	for _, e := range order {
		m := byEnv[e]
		idle, okI := m["idle"]
		or, okO := m["oracle"]
		if !okI || !okO {
			continue
		}
		span := idle.Q4 - or.Q4
		sc := func(x float64) float64 { return (x - or.Q4) / span }
		sc1 := func(x float64) float64 { return (x - or.Q1) / (idle.Q1 - or.Q1) }
		w("| %s |", e)
		for _, c := range cols {
			if a, ok := m[c]; ok {
				w(" %.2f |", sc(a.Q4))
			} else {
				w(" – |")
			}
		}
		gain := func(c string) string {
			a, ok := m[c]
			if !ok {
				return "–"
			}
			return fmt.Sprintf("%+.2f", sc1(a.Q1)-sc(a.Q4))
		}
		w(" %s / %s |\n", gain("qlearn (local)"), gain("qlearn (global)"))
	}
	w("\n")
}
